#!/usr/bin/env python3
# Compiles the graphics selftest's shaders (tri.vert, tri.frag, fill.comp, pass.geom: GLSL written for the shader library's descriptor ABI, not game code) to SPIR-V 1.3 with glslangValidator
# and writes them as word arrays into ../vka_selftest_spv.h, which vka_selftest.c includes (and nanscan.comp, the DM_VK_NANSCAN diagnostic of vka_nanscan.c). Run it after changing a shader; needs glslangValidator and spirv-val on PATH
import os, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = [("tri.vert", "SPV_TRI_VERT"), ("tri.frag", "SPV_TRI_FRAG"), ("fill.comp", "SPV_FILL_COMP"), ("nanscan.comp", "SPV_NANSCAN_COMP"), ("nanscan3.comp", "SPV_NANSCAN3_COMP"), ("fetch.comp", "SPV_FETCH_COMP"), ("pass.geom", "SPV_PASS_GEOM")]

def main():
    out = ["// Generated by dm/gfx/vk_android/selftest/spv.py from the GLSL beside it (glslangValidator -V --target-env vulkan1.1 -g0): the graphics selftest's shaders. Do not edit",
           "#pragma once", "#include <stdint.h>"]
    with tempfile.TemporaryDirectory() as tmp:
        for src, name in SHADERS:
            spv = os.path.join(tmp, src + ".spv")
            subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1", "-g0", "-o", spv, os.path.join(HERE, src)], check=True, stdout=subprocess.DEVNULL)
            subprocess.run(["spirv-val", "--target-env", "vulkan1.1", spv], check=True)
            data = open(spv, "rb").read()
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            out.append("static const uint32_t %s[%d] = {" % (name, len(words)))
            for i in range(0, len(words), 12):
                out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 12]) + ",")
            out.append("};")
    open(os.path.join(HERE, "..", "vka_selftest_spv.h"), "w").write("\n".join(out) + "\n")
    return 0

if __name__ == "__main__":
    sys.exit(main())
